#!/usr/bin/env python3
"""Generate src/backend/runtime/gql_tzdata.c: UTC offset transitions of the
named time zones GraphQLite resolves, from the IANA time zone database
(public domain) through Python's zoneinfo.

Usage: python3 scripts/gen_tzdata.py > src/backend/runtime/gql_tzdata.c

Each zone is its offset before the first transition (local mean time for
most zones) and a list of (UTC second, offset in seconds) transitions from
1800 to 2100. Run it again to take a newer tzdata release.
"""

from datetime import datetime, timedelta, timezone
from zoneinfo import ZoneInfo

ZONES = [
    "America/Anchorage", "America/Los_Angeles", "America/New_York",
    "Asia/Shanghai", "Asia/Tokyo", "Australia/Eucla", "Australia/Sydney",
    "Europe/Berlin", "Europe/London", "Europe/Paris", "Europe/Stockholm",
    "Pacific/Auckland", "Pacific/Honolulu",
]

START = datetime(1800, 1, 1, tzinfo=timezone.utc)
END = datetime(2100, 1, 1, tzinfo=timezone.utc)


def offset_at(zone, utc):
    return int(utc.astimezone(zone).utcoffset().total_seconds())


def transitions(name):
    zone = ZoneInfo(name)
    first = offset_at(zone, START)
    out = []
    step = timedelta(hours=6)
    t = START
    cur = first
    while t < END:
        nxt = t + step
        off = offset_at(zone, nxt)
        if off != cur:
            lo, hi = int(t.timestamp()), int(nxt.timestamp())
            while hi - lo > 1:  # first second with the new offset
                mid = (lo + hi) // 2
                if offset_at(zone, datetime.fromtimestamp(mid, timezone.utc)) == cur:
                    lo = mid
                else:
                    hi = mid
            out.append((hi, off))
            cur = off
        t = nxt
    return first, out


def main():
    print("/* Generated by scripts/gen_tzdata.py from the IANA time zone")
    print(" * database (public domain). Do not edit by hand. */")
    print()
    print('#include "runtime/gql_tz.h"')
    print()
    rows = []
    for name in ZONES:
        first, ts = transitions(name)
        ident = "tz_" + name.replace("/", "_").lower()
        print(f"static const gql_tz_transition {ident}[] = {{")
        for utc, off in ts:
            print(f"    {{{utc}LL, {off}}},")
        print("};")
        rows.append((name, first, ident, len(ts)))
    print()
    print("const gql_tz_zone gql_tz_zones[] = {")
    for name, first, ident, n in rows:
        print(f'    {{"{name}", {first}, {ident}, {n}}},')
    print("};")
    print(f"const int gql_tz_zone_count = {len(rows)};")


if __name__ == "__main__":
    main()
